// Stub maps for other languages — they fall back to English until translated.
const empty: Dict = {};

export const translations: Record<LangCode, Dict> = {
  en,
  fa,
  ps,
  uz,
  ar,
  tr,
  ur,
  fa_IR: fa, // Iranian Persian shares most keys with Dari; use fa dict as base.
  hi: empty,
  de: empty,
  fr: empty,
  es: empty,
  it: empty,
  pt: empty,
  nl: empty,
  sv: empty,
  no: empty,
  da: empty,
  fi: empty,
  pl: empty,
  cs: empty,
  ro: empty,
  el: empty,
  ru: empty,
  zh_CN: empty,
  zh_TW: empty,
  ja: empty,
  ko: empty,
};

export function translate(lang: LangCode, key: string): string {
  const dict = translations[lang];
  if (dict && dict[key]) return dict[key];
  // Regional fallback: fa_IR → fa, zh_TW → zh_CN, ps → fa (script similarity)
  if (lang === "fa_IR") return translations.fa[key] ?? en[key] ?? key;
  if (lang === "zh_TW") return translations.zh_CN[key] ?? en[key] ?? key;
  return en[key] ?? key;
}
